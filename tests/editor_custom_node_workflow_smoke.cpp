#include <filesystem>
#include <fstream>
#include <iostream>
#include <string>

#include "editor_composition_test_support.hpp"
#include "editor_custom_node_workflow.hpp"
#include "module_bundle.hpp"

namespace {

bool contains(const std::filesystem::path& path, std::string_view needle) {
    std::ifstream input(path, std::ios::binary);
    std::string bytes((std::istreambuf_iterator<char>(input)), std::istreambuf_iterator<char>());
    return bytes.find(needle) != std::string::npos;
}

int scaffold(const aeg::pipeline::TypeCatalogEntry& entry, aeg::application::CustomNodeKind expected_kind,
             std::string type_name, const std::filesystem::path& root) {
    aeg::application::CustomNodeScaffoldRequest request{};
    request.project_root = root;
    request.source_subdirectory = "Source/FlowGraph";
    request.namespace_name = "game::graph";
    request.type_name = std::move(type_name);
    const auto result = aeg::application::scaffold_custom_node(request, entry);
    if (!result || result.value.kind != expected_kind || result.value.files.size() != 4 ||
        result.value.implementation_target.path.empty() || result.value.registration_target.symbol.empty())
        return 1;
    for (const auto& file : result.value.files)
        if (!std::filesystem::is_regular_file(file))
            return 2;
    if (!contains(result.value.files[0], "class ") || !contains(result.value.files[0], "Generated by") ||
        !contains(result.value.files[3], "\"catalog\""))
        return 3;
    const auto metadata = aeg::module::read_module_metadata(result.value.files[3]);
    if (!metadata || !metadata.value.catalog.find(entry.key) ||
        metadata.value.catalog.find(entry.key)->ports.size() != entry.ports.size())
        return 6;
    const auto digest = aeg::module::module_contract_sha256(metadata.value);
    if (!digest || digest.value != metadata.value.contract_digest)
        return 7;
    if (aeg::application::scaffold_custom_node(request, entry))
        return 4;
    request.overwrite = true;
    if (!aeg::application::scaffold_custom_node(request, entry))
        return 5;
    return 0;
}

}  // namespace

int main(int argc, char** argv) {
    aeg::tests::EditorCompositionFixture fixture;
    const bool generate = argc == 3 && std::string_view(argv[1]) == "--generate";
    const auto root = generate ? std::filesystem::path(argv[2]) :
                                std::filesystem::temp_directory_path() / "aeg_flowgraph_custom_node_workflow_smoke";
    std::error_code error;
    std::filesystem::remove_all(root, error);
    if (scaffold(*fixture.catalog.find({aeg::pipeline::AuthoringTypeKind::kPipeline,
                                       aeg::pipeline::PipelineId("Game.EditorPipeline").value()}),
                 aeg::application::CustomNodeKind::kPipeline, "EditorPipelineNode", root) != 0)
        return 1;
    if (scaffold(*fixture.catalog.find({aeg::pipeline::AuthoringTypeKind::kFeature,
                                       aeg::pipeline::FeatureId("Game.EditorFeature").value()}),
                 aeg::application::CustomNodeKind::kFeature, "EditorFeatureNode", root) != 0)
        return 2;
    if (scaffold(*fixture.catalog.find({aeg::pipeline::AuthoringTypeKind::kRenderPass,
                                       aeg::pipeline::RenderPassTypeId("Game.EditorPass").value()}),
                 aeg::application::CustomNodeKind::kPass, "EditorPassNode", root) != 0)
        return 3;

    auto entry = *fixture.catalog.find({aeg::pipeline::AuthoringTypeKind::kFeature,
                                       aeg::pipeline::FeatureId("Game.EditorFeature").value()});
    aeg::application::CustomNodeScaffoldRequest invalid{};
    invalid.project_root = root;
    invalid.source_subdirectory = "../outside";
    invalid.type_name = "Bad";
    if (aeg::application::validate_custom_node_scaffold_request(invalid, entry))
        return 4;
    invalid.source_subdirectory = "Source";
    invalid.type_name = "bad-name";
    if (aeg::application::validate_custom_node_scaffold_request(invalid, entry))
        return 5;
    invalid.type_name = "class";
    if (aeg::application::validate_custom_node_scaffold_request(invalid, entry))
        return 6;
    if (!generate)
        std::filesystem::remove_all(root, error);
    std::cout << "Editor custom node workflow smoke passed\n";
    return 0;
}
